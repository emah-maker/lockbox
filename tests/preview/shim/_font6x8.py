def _build():
    glyphs = {}
    for ch, rows in _RAW.items():
        assert len(rows) == GLYPH_H, ch
        packed = []
        for row in rows:
            assert len(row) == GLYPH_W, ch
            packed.append([bit == "1" for bit in row])
        glyphs[ord(ch)] = packed
    return glyphs


# codepoint -> list[GLYPH_H][GLYPH_W] of bool ("on"/"off"), padded on read
# (see get_glyph) to the full ADVANCE_W x ADVANCE_H box with blank cells.
GLYPHS = _build()

_BLANK_ROW = [False] * ADVANCE_W


def get_glyph(codepoint):
    """Returns an ADVANCE_H-row list of ADVANCE_W-bool rows for `codepoint`,
    falling back to a blank cell for anything outside 32-126 (real
    terminalio.FONT would raise -- firmware never sends non-ASCII, so this
    degrades instead of crashing a preview render)."""
    rows = GLYPHS.get(codepoint)
    if rows is None:
        return [_BLANK_ROW] * ADVANCE_H
    out = []
    for row in rows:
        out.append(row + [False] * (ADVANCE_W - GLYPH_W))
    out.append(_BLANK_ROW)
    return out
