# _font6x8.py -- hand-authored 5x7 glyph bitmaps, padded to a 6x8 advance
# box, standing in for the real terminalio.FONT.
#
# WHY THIS EXISTS / WHAT IT IS NOT: the real terminalio.FONT is a fixed 6x8px
# bitmap font baked into CircuitPython's core -- its exact pixel data is not
# available on the host (it isn't a file on disk, it's compiled into the
# firmware binary), so there is nothing to load or convert here. This module
# is an ORIGINAL, hand-drawn 5x7 pixel font -- generic, unremarkable block
# letterforms of the kind that recur independently across countless tiny
# pixel fonts, not a reproduction of any specific existing font's bitmap
# data -- covering ASCII 32-126, with a blank column and row of padding to
# fill out a 6-wide x 8-tall advance box.
#
# What IS exact: the metrics. terminalio.FONT's glyph advance is 6*scale
# pixels wide and 8*scale pixels tall, unconditionally -- that spacing is
# what firmware layout math (label widths, row pitches, anchor centering)
# actually depends on, and this shim reproduces it precisely. Only the
# glyph SHAPES themselves are a stand-in; see tests/preview/README.md's
# fidelity-limits section.
#
# Each entry is 7 rows of a 5-char '0'/'1' string (column 0 = leftmost of
# the 5 visible columns). Row 7 (index 7, 0-based) and column 5 are always
# blank -- that's the padding that turns 5x7 into the 6x8 advance box.
# Lowercase descenders (g, j, p, q, y) use row 6 (the glyph's last row)
# instead of a true below-baseline descender, since there is no 8th glyph
# row to spare -- they will look slightly "sat on the baseline" rather than
# hanging below it. Documented, not hidden: see the README.

GLYPH_W = 5     # visible glyph pixels, left-to-right
GLYPH_H = 7     # visible glyph pixels, top-to-bottom
ADVANCE_W = 6   # terminalio.FONT's real, exact per-glyph advance
ADVANCE_H = 8   # terminalio.FONT's real, exact per-glyph line height

